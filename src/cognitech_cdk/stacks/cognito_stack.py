"""Cognito user pools with their clients, domains, federation and identity pools."""

from __future__ import annotations

from typing import Mapping

import aws_cdk as cdk
from aws_cdk import aws_certificatemanager as acm
from aws_cdk import aws_cognito as cognito
from aws_cdk import aws_lambda as lambda_
from aws_cdk import aws_secretsmanager as secretsmanager
from constructs import Construct

from cognitech_cdk.common import schema
from cognitech_cdk.common.environment import Environment
from cognitech_cdk.constructs.cognito import (
    POOL_NAME,
    ClientProps,
    CognitoProps,
    UserPoolProps,
)
from cognitech_cdk.constructs.lambdas import construct_id as logical_id
from cognitech_cdk.constructs.lambdas import export_key
from cognitech_cdk.stacks.base import EnvironmentStack

C = cognito.CfnUserPool


class CognitoStack(EnvironmentStack):
    """`cognito` from the environment YAML.

    Client secrets are generated by Cognito when asked for, but never read
    back: they appear in no output, secret or custom-resource response.
    """

    def __init__(
        self,
        scope: Construct,
        construct_id: str,
        *,
        environment: Environment,
        props: CognitoProps,
        certificates: Mapping[str, acm.ICertificate] | None = None,
        functions: Mapping[str, lambda_.IFunction] | None = None,
        **kwargs,
    ) -> None:
        super().__init__(scope, construct_id, environment=environment, **kwargs)
        self.props = props
        self._certificates = certificates or {}
        self._functions = functions or {}

        self.user_pools: dict[str, cognito.IUserPool] = {}
        self.cfn_user_pools: dict[str, cognito.CfnUserPool] = {}
        self.clients: dict[str, dict[str, cognito.IUserPoolClient]] = {}
        self.domains: dict[str, cognito.CfnUserPoolDomain] = {}
        self.identity_providers: dict[str, dict[str, cognito.CfnUserPoolIdentityProvider]] = {}
        self.resource_servers: dict[str, dict[str, cognito.CfnUserPoolResourceServer]] = {}
        self.user_groups: dict[str, dict[str, cognito.CfnUserPoolGroup]] = {}
        self.identity_pools: dict[str, cognito.CfnIdentityPool] = {}
        self.secrets: dict[str, secretsmanager.CfnSecret] = {}
        self.trigger_permissions: dict[str, dict[str, lambda_.CfnPermission]] = {}

        for pool in props.user_pools:
            self._add_pool(pool)

    def _add_pool(self, props: UserPoolProps) -> None:
        label = f"Cognito '{props.name}'"
        name = self.resource_name(props.name)
        if not POOL_NAME.fullmatch(name):
            raise ValueError(f"{label}: user pool name '{name}' is longer than 128 characters.")
        cid = logical_id(props.name)
        scope = Construct(self, cid)
        removal = (
            cdk.RemovalPolicy.DESTROY if props.removal_policy == "destroy"
            else cdk.RemovalPolicy.RETAIN
        )
        triggers = {
            trigger: (
                value if value.startswith("arn:")
                else schema.lookup(
                    self._functions, value, f"{label}.lambda_config"
                ).function_arn
            )
            for trigger, value in props.lambda_triggers.items()
        }

        pool = cognito.CfnUserPool(
            scope, "UserPool", **self._pool_properties(props, name, triggers)
        )
        pool.apply_removal_policy(removal)
        cdk.Tags.of(pool).add("Name", name)
        for key, value in props.tags.items():
            cdk.Tags.of(pool).add(key, value)
        self.cfn_user_pools[props.name] = pool
        self.user_pools[props.name] = cognito.UserPool.from_user_pool_arn(
            scope, "UserPoolReference", pool.attr_arn
        )

        self.trigger_permissions[props.name] = {}
        if props.create_lambda_permissions:
            for trigger, function_arn in triggers.items():
                self.trigger_permissions[props.name][trigger] = lambda_.CfnPermission(
                    scope,
                    f"AllowCognito{trigger}",
                    action="lambda:InvokeFunction",
                    function_name=function_arn,
                    principal="cognito-idp.amazonaws.com",
                    source_arn=pool.attr_arn,
                )

        servers = {
            server.identifier: cognito.CfnUserPoolResourceServer(
                scope,
                f"ResourceServer{index}",
                user_pool_id=pool.ref,
                identifier=server.identifier,
                name=server.name,
                scopes=[
                    cognito.CfnUserPoolResourceServer.ResourceServerScopeTypeProperty(
                        scope_name=scope_name, scope_description=description
                    )
                    for scope_name, description in server.scopes
                ] or None,
            )
            for index, server in enumerate(props.resource_servers)
        }
        self.resource_servers[props.name] = servers

        providers = {
            idp.provider_name: cognito.CfnUserPoolIdentityProvider(
                scope,
                f"IdentityProvider{index}",
                user_pool_id=pool.ref,
                provider_name=idp.provider_name,
                provider_type=idp.provider_type,
                provider_details=dict(idp.provider_details),
                attribute_mapping=dict(idp.attribute_mapping) or None,
                idp_identifiers=list(idp.idp_identifiers) or None,
            )
            for index, idp in enumerate(props.identity_providers)
        }
        self.identity_providers[props.name] = providers

        clients: dict[str, cognito.CfnUserPoolClient] = {}
        for client in props.clients:
            resource = self._client(scope, pool, client)
            for dependency in (*servers.values(), *providers.values()):
                resource.add_resource_dependency(dependency)
            clients[client.name] = resource
        self.clients[props.name] = {
            client_name: cognito.UserPoolClient.from_user_pool_client_id(
                scope, f"Client{logical_id(client_name)}Reference", resource.ref
            )
            for client_name, resource in clients.items()
        }

        if props.domain is not None:
            certificate_arn = props.domain.certificate_arn
            if props.domain.certificate is not None:
                certificate_arn = schema.lookup(
                    self._certificates, props.domain.certificate, f"{label}.domain.certificate"
                ).certificate_arn
            self.domains[props.name] = cognito.CfnUserPoolDomain(
                scope,
                "Domain",
                domain=props.domain.domain_name,
                user_pool_id=pool.ref,
                custom_domain_config=(
                    cognito.CfnUserPoolDomain.CustomDomainConfigTypeProperty(
                        certificate_arn=certificate_arn
                    )
                    if certificate_arn is not None else None
                ),
            )

        self.user_groups[props.name] = {
            group.name: cognito.CfnUserPoolGroup(
                scope,
                f"Group{index}",
                user_pool_id=pool.ref,
                group_name=group.name,
                description=group.description,
                precedence=group.precedence,
                role_arn=group.role_arn,
            )
            for index, group in enumerate(props.user_groups)
        }

        if props.identity_pool.create:
            self._identity_pool(scope, props, name, pool, clients, removal)
        if props.secret.create:
            self._secret(scope, props, name, pool, clients, removal)

        self._outputs(props, cid, name, pool, clients)

    def _pool_properties(
        self, props: UserPoolProps, name: str, triggers: Mapping[str, str]
    ) -> dict:
        policy = props.password_policy
        email = props.email_configuration
        admin = props.admin_create_user_config
        verification = props.verification_message_template
        enabled_mfas = []
        if props.mfa_configuration != "OFF":
            if props.software_token_mfa_enabled:
                enabled_mfas.append("SOFTWARE_TOKEN_MFA")
            if props.sms_configuration is not None:
                enabled_mfas.append("SMS_MFA")
        lambda_config = None
        if triggers or props.lambda_kms_key_id:
            lambda_config = C.LambdaConfigProperty(
                kms_key_id=props.lambda_kms_key_id,
                **{_snake(trigger): arn for trigger, arn in triggers.items()},
            )
        return {
            "user_pool_name": name,
            "deletion_protection": props.deletion_protection,
            "alias_attributes": list(props.alias_attributes) if props.alias_attributes else None,
            "username_attributes": (
                list(props.username_attributes) if props.username_attributes else None
            ),
            "auto_verified_attributes": list(props.auto_verified_attributes) or None,
            "mfa_configuration": props.mfa_configuration,
            "enabled_mfas": enabled_mfas or None,
            "username_configuration": C.UsernameConfigurationProperty(
                case_sensitive=props.username_case_sensitive
            ),
            "policies": C.PoliciesProperty(
                password_policy=C.PasswordPolicyProperty(
                    minimum_length=policy.minimum_length,
                    require_lowercase=policy.require_lowercase,
                    require_numbers=policy.require_numbers,
                    require_symbols=policy.require_symbols,
                    require_uppercase=policy.require_uppercase,
                    temporary_password_validity_days=policy.temporary_password_validity_days,
                )
            ),
            "sms_configuration": (
                C.SmsConfigurationProperty(
                    external_id=props.sms_configuration.external_id,
                    sns_caller_arn=props.sms_configuration.sns_caller_arn,
                    sns_region=props.sms_configuration.sns_region,
                )
                if props.sms_configuration is not None else None
            ),
            "email_configuration": C.EmailConfigurationProperty(
                email_sending_account=email.email_sending_account,
                from_=email.from_email_address,
                reply_to_email_address=email.reply_to_email_address,
                source_arn=email.source_arn,
                configuration_set=email.configuration_set,
            ),
            "admin_create_user_config": C.AdminCreateUserConfigProperty(
                allow_admin_create_user_only=admin.allow_admin_create_user_only,
                invite_message_template=(
                    C.InviteMessageTemplateProperty(
                        email_subject=admin.invite_email_subject,
                        email_message=admin.invite_email_message,
                        sms_message=admin.invite_sms_message,
                    )
                    if admin.has_invite_template else None
                ),
            ),
            "device_configuration": C.DeviceConfigurationProperty(
                challenge_required_on_new_device=props.challenge_required_on_new_device,
                device_only_remembered_on_user_prompt=props.device_only_remembered_on_user_prompt,
            ),
            "user_pool_add_ons": (
                C.UserPoolAddOnsProperty(advanced_security_mode=props.advanced_security_mode)
                if props.advanced_security_mode != "OFF" else None
            ),
            "schema": [
                C.SchemaAttributeProperty(
                    name=attribute.name,
                    attribute_data_type=attribute.attribute_data_type,
                    developer_only_attribute=attribute.developer_only_attribute,
                    mutable=attribute.mutable,
                    required=attribute.required,
                    string_attribute_constraints=(
                        C.StringAttributeConstraintsProperty(**attribute.string_constraints)
                        if attribute.string_constraints else None
                    ),
                    number_attribute_constraints=(
                        C.NumberAttributeConstraintsProperty(**attribute.number_constraints)
                        if attribute.number_constraints else None
                    ),
                )
                for attribute in props.schema_attributes
            ] or None,
            "verification_message_template": C.VerificationMessageTemplateProperty(
                default_email_option=verification.default_email_option,
                email_message=verification.email_message,
                email_message_by_link=verification.email_message_by_link,
                email_subject=verification.email_subject,
                email_subject_by_link=verification.email_subject_by_link,
                sms_message=verification.sms_message,
            ),
            "lambda_config": lambda_config,
        }

    def _client(
        self, scope: Construct, pool: cognito.CfnUserPool, props: ClientProps
    ) -> cognito.CfnUserPoolClient:
        return cognito.CfnUserPoolClient(
            scope,
            f"Client{logical_id(props.name)}",
            user_pool_id=pool.ref,
            client_name=props.name,
            generate_secret=props.generate_secret,
            explicit_auth_flows=list(props.explicit_auth_flows) or None,
            allowed_o_auth_flows=list(props.allowed_oauth_flows) or None,
            allowed_o_auth_flows_user_pool_client=props.allowed_oauth_flows_user_pool_client,
            allowed_o_auth_scopes=list(props.allowed_oauth_scopes) or None,
            callback_ur_ls=list(props.callback_urls) or None,
            logout_ur_ls=list(props.logout_urls) or None,
            default_redirect_uri=props.default_redirect_uri,
            supported_identity_providers=list(props.supported_identity_providers) or None,
            prevent_user_existence_errors=props.prevent_user_existence_errors,
            refresh_token_validity=props.refresh_token_validity,
            access_token_validity=props.access_token_validity,
            id_token_validity=props.id_token_validity,
            token_validity_units=cognito.CfnUserPoolClient.TokenValidityUnitsProperty(
                access_token=props.access_token_unit,
                id_token=props.id_token_unit,
                refresh_token=props.refresh_token_unit,
            ),
            read_attributes=(
                list(props.read_attributes) if props.read_attributes is not None else None
            ),
            write_attributes=(
                list(props.write_attributes) if props.write_attributes is not None else None
            ),
            enable_token_revocation=props.enable_token_revocation,
            enable_propagate_additional_user_context_data=(
                props.enable_propagate_additional_user_context_data
            ),
        )

    def _identity_pool(
        self,
        scope: Construct,
        props: UserPoolProps,
        name: str,
        pool: cognito.CfnUserPool,
        clients: Mapping[str, cognito.CfnUserPoolClient],
        removal: cdk.RemovalPolicy,
    ) -> None:
        settings = props.identity_pool
        pool_name = settings.name or f"{name}-identity-pool"
        if not POOL_NAME.fullmatch(pool_name):
            raise ValueError(
                f"Cognito '{props.name}': identity pool name '{pool_name}' is too long."
            )
        providers = [
            cognito.CfnIdentityPool.CognitoIdentityProviderProperty(
                client_id=client.ref,
                provider_name=pool.attr_provider_name,
                server_side_token_check=settings.server_side_token_check,
            )
            for client in clients.values()
        ] + [
            cognito.CfnIdentityPool.CognitoIdentityProviderProperty(
                client_id=extra.client_id,
                provider_name=extra.provider_name,
                server_side_token_check=extra.server_side_token_check,
            )
            for extra in settings.additional_cognito_providers
        ]
        identity_pool = cognito.CfnIdentityPool(
            scope,
            "IdentityPool",
            identity_pool_name=pool_name,
            allow_unauthenticated_identities=settings.allow_unauthenticated_identities,
            allow_classic_flow=settings.allow_classic_flow,
            cognito_identity_providers=providers or None,
        )
        identity_pool.apply_removal_policy(removal)
        cdk.Tags.of(identity_pool).add("Name", pool_name)
        for key, value in props.tags.items():
            cdk.Tags.of(identity_pool).add(key, value)
        roles = {
            role: arn
            for role, arn in (
                ("authenticated", settings.authenticated_role_arn),
                ("unauthenticated", settings.unauthenticated_role_arn),
            )
            if arn is not None
        }
        if roles:
            cognito.CfnIdentityPoolRoleAttachment(
                scope, "IdentityPoolRoles", identity_pool_id=identity_pool.ref, roles=roles
            )
        self.identity_pools[props.name] = identity_pool

    def _secret(
        self,
        scope: Construct,
        props: UserPoolProps,
        name: str,
        pool: cognito.CfnUserPool,
        clients: Mapping[str, cognito.CfnUserPoolClient],
        removal: cdk.RemovalPolicy,
    ) -> None:
        # Identifiers only. Terraform also copied the primary client's secret;
        # reading it would need a custom resource returning the secret, so it
        # is deliberately left out.
        payload: dict[str, str] = {
            "COGNITO_USER_POOL_ID": pool.ref,
            "COGNITO_REGION": self.region,
            "COGNITO_USER_POOL_ARN": pool.attr_arn,
            "COGNITO_USER_POOL_NAME": name,
            "COGNITO_USER_POOL_ENDPOINT": pool.attr_provider_name,
        }
        primary = props.secret_primary_client
        if primary is not None:
            payload["COGNITO_PRIMARY_CLIENT_NAME"] = primary
            payload["COGNITO_PRIMARY_CLIENT_ID"] = clients[primary].ref
        if props.name in self.domains:
            payload["COGNITO_DOMAIN"] = props.domain.domain_name
        if props.name in self.identity_pools:
            payload["COGNITO_IDENTITY_POOL_ID"] = self.identity_pools[props.name].ref
        payload.update(props.secret.additional_values)
        secret_name = props.secret.name or f"{name}/cognito"
        secret = secretsmanager.CfnSecret(
            scope,
            "ConfigSecret",
            name=secret_name,
            description=(
                props.secret.description or f"Cognito user pool config for {name}"
            ),
            kms_key_id=props.secret.kms_key_id,
            secret_string=self.to_json_string(payload),
        )
        secret.apply_removal_policy(removal)
        cdk.Tags.of(secret).add("Name", secret_name)
        self.secrets[props.name] = secret

    def _outputs(
        self,
        props: UserPoolProps,
        cid: str,
        name: str,
        pool: cognito.CfnUserPool,
        clients: Mapping[str, cognito.CfnUserPoolClient],
    ) -> None:
        key = export_key(props.name)
        self.output(f"{cid}UserPoolId", pool.ref, f"{key}-user-pool-id")
        self.output(f"{cid}UserPoolArn", pool.attr_arn, f"{key}-user-pool-arn")
        self.output(f"{cid}UserPoolName", name, f"{key}-user-pool-name")
        self.output(
            f"{cid}UserPoolProviderName", pool.attr_provider_name,
            f"{key}-user-pool-provider-name",
        )
        for client_name, client in clients.items():
            self.output(
                f"{cid}Client{logical_id(client_name)}Id", client.ref,
                f"{key}-client-{export_key(client_name)}-id",
            )
        if props.name in self.domains:
            domain = self.domains[props.name]
            self.output(f"{cid}DomainName", props.domain.domain_name, f"{key}-domain-name")
            self.output(
                f"{cid}DomainCloudFrontDistribution", domain.attr_cloud_front_distribution,
                f"{key}-domain-cloudfront-distribution",
            )
        if props.name in self.identity_pools:
            self.output(
                f"{cid}IdentityPoolId", self.identity_pools[props.name].ref,
                f"{key}-identity-pool-id",
            )
        if props.name in self.secrets:
            self.output(f"{cid}SecretArn", self.secrets[props.name].ref, f"{key}-secret-arn")


def _snake(trigger: str) -> str:
    """`PreSignUp` -> `pre_sign_up`, the CfnUserPool.LambdaConfigProperty keyword."""
    return "".join(f"_{char.lower()}" if char.isupper() else char for char in trigger).lstrip("_")
